BEGIN;

CREATE SCHEMA exam_scanner;
REVOKE ALL ON SCHEMA exam_scanner FROM PUBLIC;
SET LOCAL search_path = exam_scanner, pg_catalog;

CREATE TABLE exams (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL,
    total_items integer NOT NULL,
    answer_key text NOT NULL,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE scan_jobs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id integer NOT NULL REFERENCES exams(id) ON DELETE CASCADE ON UPDATE CASCADE,
    status varchar(30) NOT NULL,
    raw_payload json,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX scan_jobs_exam_id_idx ON scan_jobs (exam_id);

CREATE TABLE submissions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id integer NOT NULL REFERENCES exams(id) ON DELETE CASCADE ON UPDATE CASCADE,
    exam_title varchar(200),
    student_code varchar(64) NOT NULL,
    answers text NOT NULL,
    score integer NOT NULL,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX submissions_exam_student_created_idx ON submissions (exam_id, student_code, created_at);
CREATE INDEX submissions_student_code_idx ON submissions (student_code);

CREATE TABLE educators (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    surname varchar(180) NOT NULL,
    email varchar(180) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    profile_photo_data text,
    is_active smallint NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at timestamp DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp DEFAULT CURRENT_TIMESTAMP
);

CREATE FUNCTION exam_scanner.set_educator_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER educators_set_updated_at BEFORE UPDATE ON educators
FOR EACH ROW EXECUTE FUNCTION exam_scanner.set_educator_updated_at();

CREATE TABLE subjects (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    educator_id integer NOT NULL REFERENCES educators(id) ON DELETE CASCADE ON UPDATE CASCADE,
    subject_code varchar(40) NOT NULL,
    title varchar(160) NOT NULL,
    term_label varchar(80),
    description text,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (educator_id, subject_code)
);

CREATE TABLE students (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_code varchar(64) NOT NULL UNIQUE,
    surname varchar(180) NOT NULL,
    given_name varchar(120),
    middle_name varchar(120),
    email varchar(180),
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE subject_students (
    subject_id integer NOT NULL REFERENCES subjects(id) ON DELETE CASCADE ON UPDATE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE ON UPDATE CASCADE,
    enrolled_at timestamp DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (subject_id, student_id)
);
CREATE INDEX subject_students_student_id_idx ON subject_students (student_id);

CREATE TABLE subject_activities (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id integer NOT NULL REFERENCES subjects(id) ON DELETE CASCADE ON UPDATE CASCADE,
    title varchar(180) NOT NULL,
    activity_type varchar(24) NOT NULL DEFAULT 'exam',
    exam_id integer REFERENCES exams(id) ON DELETE SET NULL ON UPDATE CASCADE,
    exam_code char(6) UNIQUE,
    max_score integer NOT NULL DEFAULT 100,
    due_at timestamp,
    grading_period varchar(2) CHECK (grading_period IN ('Q1', 'Q2', 'Q3', 'Q4')),
    publish_status varchar(16) NOT NULL DEFAULT 'draft',
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX subject_activities_subject_id_idx ON subject_activities (subject_id);
CREATE INDEX subject_activities_exam_id_idx ON subject_activities (exam_id);

CREATE TABLE subject_activity_scores (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id integer NOT NULL REFERENCES subject_activities(id) ON DELETE CASCADE ON UPDATE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE ON UPDATE CASCADE,
    score numeric(8,2),
    recorded_at timestamp DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (activity_id, student_id)
);
CREATE INDEX subject_activity_scores_student_id_idx ON subject_activity_scores (student_id);

CREATE TABLE subject_grade_weights (
    subject_id integer PRIMARY KEY REFERENCES subjects(id) ON DELETE CASCADE ON UPDATE CASCADE,
    written_work_weight numeric(5,2) NOT NULL DEFAULT 0,
    performance_task_weight numeric(5,2) NOT NULL DEFAULT 0,
    quarterly_assessment_weight numeric(5,2) NOT NULL DEFAULT 0
);

CREATE TABLE subject_announcements (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id integer NOT NULL REFERENCES subjects(id) ON DELETE CASCADE ON UPDATE CASCADE,
    title varchar(180) NOT NULL,
    body text NOT NULL,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX subject_announcements_subject_id_idx ON subject_announcements (subject_id);

CREATE TABLE scan_staging (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id varchar(36) NOT NULL,
    sheet_index integer NOT NULL,
    student_code char(6),
    exam_code char(6),
    raw_answers varchar(120),
    score integer,
    max_score integer,
    status varchar(7) NOT NULL DEFAULT 'ok' CHECK (status IN ('ok', 'flagged')),
    flag_reasons text,
    scan_image text,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX scan_staging_session_sheet_idx ON scan_staging (session_id, sheet_index);

CREATE ROLE exam_scanner_app NOLOGIN;
GRANT USAGE ON SCHEMA exam_scanner TO exam_scanner_app;
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA exam_scanner TO exam_scanner_app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA exam_scanner TO exam_scanner_app;
GRANT UPDATE ON educators, students, subjects, subject_activities, subject_activity_scores,
    subject_grade_weights, subject_announcements TO exam_scanner_app;
GRANT DELETE ON subjects, subject_students, subject_activities, subject_announcements,
    scan_staging TO exam_scanner_app;

COMMIT;
