"""Outbound connection from the scanner PC to the educator's paired website."""

from __future__ import annotations

import logging
import re
import time
import uuid
from urllib.parse import urlsplit

import requests

logger = logging.getLogger(__name__)
SESSION_ID = re.compile(r"[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}")
SCANNER_TOKEN = re.compile(r"[0-9a-f]{64}")
POLL_INTERVAL_SECONDS = 3
STOP_AFTER_DISCONNECT_SECONDS = 15


class OnlineScanner:
    def __init__(self, api_url: str, token: str, simulate: bool = False) -> None:
        url = urlsplit(api_url)
        loopback = url.hostname in {"127.0.0.1", "localhost", "::1"}
        allowed = url.scheme == "https" or (simulate and loopback and url.scheme == "http")
        if not allowed or not url.hostname or url.username or url.password or url.query or url.fragment:
            raise ValueError("Use the website's HTTPS API URL.")
        if simulate and not loopback:
            raise ValueError("Simulation requires a local test website.")
        if not SCANNER_TOKEN.fullmatch(token):
            raise ValueError("Enter the scanner code generated by the website.")
        self.url = api_url.rstrip("/") + "/scanner/device"
        self.headers = {
            "Authorization": f"Bearer {token}",
            "X-Scanner-Worker": uuid.uuid4().hex,
        }

    def _request(self, method: str, endpoint: str, **kwargs) -> requests.Response:
        # A redirect must never forward the scanner code to another destination.
        response = requests.request(
            method, self.url + endpoint, headers=self.headers,
            timeout=(3, 7), allow_redirects=False, **kwargs,
        )
        if response.status_code >= 300:
            if 300 <= response.status_code < 400:
                raise requests.HTTPError("Unexpected scanner API redirect", response=response)
            response.raise_for_status()
        return response

    def fetch_answer_key(self, session_id: str, exam_code: str) -> dict | None:
        try:
            response = self._request("GET", f"/session/{session_id}/exam-code/{exam_code}")
        except requests.HTTPError as error:
            if error.response is not None and error.response.status_code == 404:
                return None
            raise
        return response.json()["data"]

    def post_sheet(self, session_id: str, result: dict) -> None:
        for attempt in range(3):
            try:
                self._request("POST", f"/session/{session_id}/sheet", json=result)
                return
            except requests.RequestException as error:
                response = getattr(error, "response", None)
                if attempt == 2 or (response is not None and 400 <= response.status_code < 500):
                    raise
                time.sleep(1)

    def run(self, state, hardware_status, start_scan) -> None:
        last_poll = time.monotonic()
        last_started_session = None
        try:
            while True:
                snapshot = state.snapshot()
                try:
                    scanner_ready, arduino_ready = hardware_status()
                    response = self._request("POST", "/poll", json={
                        **snapshot, "scanner_ready": scanner_ready, "arduino_ready": arduino_ready,
                    })
                    job = response.json()["data"]["job"]
                except (requests.RequestException, KeyError, TypeError, ValueError) as error:
                    response = getattr(error, "response", None)
                    status = response.status_code if response is not None else None
                    if status == 401:
                        raise RuntimeError("Scanner code rejected. Pair the scanner PC again.") from error
                    if state.is_running and (status == 409 or time.monotonic() - last_poll >= STOP_AFTER_DISCONNECT_SECONDS):
                        state.request_stop()
                    logger.warning("Scanner website connection could not be confirmed: %s", error)
                else:
                    last_poll = time.monotonic()
                    if job is None:
                        if state.is_running:
                            state.request_stop()
                    else:
                        session_id = job["session_id"]
                        if not SESSION_ID.fullmatch(session_id):
                            raise RuntimeError("The scanner received an invalid session ID.")
                        active = snapshot["active_session_id"]
                        if active and (active != session_id or job["stop"]):
                            state.request_stop()
                        elif not active and session_id != last_started_session:
                            last_started_session = session_id
                            single = job["single"]
                            if job["stop"]:
                                state.end_batch(session_id, "stopped", "Scan stopped before the feeder started.")
                            elif not scanner_ready or (not single and not arduino_ready):
                                state.end_batch(session_id, "hardware_error", "The scanner or feeder became unavailable.")
                            else:
                                start_scan(session_id, single)
                time.sleep(POLL_INTERVAL_SECONDS if state.is_running else 5)
        finally:
            state.request_stop()
            state.wait_until_idle()
